/** Texte de la langue demandée, sinon français, sinon la clé (jamais vide). */
export const translate = (language: Language, key: string, params?: Record<string, string | number>): string => {
  let text = translations[language]?.[key] || translations[DEFAULT_LANGUAGE][key] || key;
  if (params) {
    Object.keys(params).forEach((param) => {
      text = text.replace(new RegExp(`{{${param}}}`, 'g'), String(params[param]));
    });
  }
  return text;
};
